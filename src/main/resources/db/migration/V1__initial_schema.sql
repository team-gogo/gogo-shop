CREATE TABLE tbl_shop (
    shop_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stage_id BIGINT NOT NULL UNIQUE,
    is_active_game VARCHAR(255) NOT NULL
);

CREATE TABLE tbl_coin_toss (
    coin_toss_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shop_id BIGINT NOT NULL UNIQUE,
    ticket_price BIGINT NOT NULL,
    ticket_qauntity INTEGER NOT NULL
);

CREATE TABLE tbl_plinko (
    plinko_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shop_id BIGINT NOT NULL UNIQUE,
    ticket_price BIGINT NOT NULL,
    ticket_qauntity INTEGER NOT NULL
);

CREATE TABLE tbl_yavarwee (
    yavarwee_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shop_id BIGINT NOT NULL UNIQUE,
    ticket_price BIGINT NOT NULL,
    ticket_qauntity INTEGER NOT NULL
);

CREATE TABLE tbl_shop_receipt (
    shop_receipt_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shop_id BIGINT NOT NULL,
    student_id BIGINT NOT NULL,
    ticket_qauntity INTEGER NOT NULL,
    ticket_price BIGINT NOT NULL,
    ticket_type VARCHAR(255) NOT NULL,
    purchase_date TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    purchase_status VARCHAR(255) NOT NULL
);
